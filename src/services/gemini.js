// ------------------ Gemini API Core Call & Backoff ------------------
async function callGemini(prompt, systemPrompt = 'You are a helpful environmental and carbon credit expert.') {
  const apiKey = ''; // API key is blank as required for runtime injection
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-preview-09-2025:generateContent?key=${apiKey}`;

  const payload = {
    contents: [{ parts: [{ text: prompt }] }],
    systemInstruction: { parts: [{ text: systemPrompt }] },
  };

  let delay = 1000;
  // Retry up to 5 times with exponential backoff (1s, 2s, 4s, 8s, 16s)
  for (let i = 0; i < 5; i++) {
    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });
      if (response.ok) {
        const result = await response.json();
        return result.candidates?.[0]?.content?.parts?.[0]?.text || 'ไม่สามารถดึงข้อมูลคำตอบจาก AI ได้';
      }
    } catch (error) {
      // Fail silently during retries
    }
    await new Promise((resolve) => setTimeout(resolve, delay));
    delay *= 2;
  }
  throw new Error('ขออภัย ขัดข้องทางเทคนิคเนื่องจากส่งสัญญาณคำขอมากเกินไป กรุณาลองใหม่อีกครั้งในภายหลัง');
}

